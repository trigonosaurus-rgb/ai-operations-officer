"""Retrieval eval: vector vs. BM25 vs. hybrid (RRF) on labeled queries.

Usage (from backend/; no API key needed, runs locally in seconds):
    uv run python -m evals.retrieval

Metrics per retriever (k = RETRIEVAL_TOP_K, the number of passages the agent sees):
    hit@1   the first passage is relevant
    hit@k   at least one of the k passages is relevant  (can the agent answer at all?)
    MRR     mean reciprocal rank of the first relevant passage (how high it ranks)
Writes evals/results/retrieval.md.
"""

import sys
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import yaml
from llama_index.core.schema import NodeWithScore

from app.agent.tools.documents import DocumentIndex
from app.config import get_settings

EVALS_DIR = Path(__file__).parent


@dataclass
class Case:
    query: str
    docs: list[str]
    contains: str


def norm(text: str) -> str:
    return " ".join(text.lower().split())


def is_relevant(hit: NodeWithScore, case: Case) -> bool:
    return hit.node.metadata["slug"] in case.docs and norm(case.contains) in norm(
        hit.node.get_content()
    )


def first_relevant_rank(hits: list[NodeWithScore], case: Case) -> int | None:
    return next((i for i, h in enumerate(hits, start=1) if is_relevant(h, case)), None)


def check_labels(index: DocumentIndex, cases: list[Case]) -> None:
    """A label whose text exists in no chunk can never be hit: that's a labeling bug."""
    for c in cases:
        if not any(is_relevant(NodeWithScore(node=n), c) for n in index.nodes):
            sys.exit(f"Bad label: no chunk of {c.docs} contains {c.contains!r}")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    settings = get_settings()
    k = settings.retrieval_top_k
    raw = yaml.safe_load((EVALS_DIR / "retrieval_cases.yaml").read_text(encoding="utf-8"))
    cases = [Case(**c) for c in raw]
    index = DocumentIndex.load_or_build(settings)
    check_labels(index, cases)

    retrievers: dict[str, Callable[[str], list[NodeWithScore]]] = {
        "Vector (bge-small)": index.vector.retrieve,
        "BM25": index.bm25.retrieve,
        "Hybrid (RRF)": index.retriever.retrieve,
    }
    ranks = {
        name: [first_relevant_rank(fn(c.query), c) for c in cases]
        for name, fn in retrievers.items()
    }

    n = len(cases)
    lines = [
        "# Retrieval eval results",
        "",
        f"{n} labeled queries · {len(index.nodes)} chunks · k = {k} · "
        f"run {datetime.now(UTC):%Y-%m-%d %H:%M UTC}",
        "",
        "Generated by `uv run python -m evals.retrieval` — do not edit by hand.",
        "",
        "| Retriever | hit@1 | hit@k | MRR |",
        "|---|---|---|---|",
    ]
    for name, rs in ranks.items():
        hit1 = sum(r == 1 for r in rs) / n
        hitk = sum(r is not None for r in rs) / n
        mrr = sum(1 / r for r in rs if r) / n
        lines.append(f"| {name} | {hit1:.0%} | {hitk:.0%} | {mrr:.2f} |")
        print(f"{name:<20} hit@1 {hit1:5.0%}   hit@{k} {hitk:5.0%}   MRR {mrr:.2f}")

    lines += ["", "## Per query (rank of the first relevant passage, — = not in top k)", ""]
    lines += ["| Query | " + " | ".join(ranks) + " |", "|---|" + "---|" * len(ranks)]
    for i, c in enumerate(cases):
        cells = [str(ranks[name][i] or "—") for name in ranks]
        lines.append(f"| {c.query} | " + " | ".join(cells) + " |")

    out = EVALS_DIR / "results" / "retrieval.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Report: {out.relative_to(EVALS_DIR.parent)}")


if __name__ == "__main__":
    main()
